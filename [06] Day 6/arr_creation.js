// array creation
let nums = [1, 2, 3, 4, 5];
console.log(nums);

console.log(nums[0]);
console.log(nums[nums.length - 1]);

// array methods
nums.push(6);
console.log(nums);

nums.pop();
console.log(nums);

nums.shift(); // removes 1st element
console.log(nums);

nums.unshift(7); // adds an element in 1st position i.e 0th index
console.log(nums);

